/* translator */
window.LLT = function (key, vars) {
  const lang = (window.LLLang && window.LLLang.current) || 'ar';
  const dict = window.LL_I18N[lang] || {};
  let s = dict[key];
  if (typeof s !== 'string') s = window.LL_I18N.ar[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return s;
};
